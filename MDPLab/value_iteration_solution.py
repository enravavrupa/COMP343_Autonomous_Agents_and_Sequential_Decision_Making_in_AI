"""
value_iteration_solution.py — reference solver (already complete)
====================================================================

This is the "inbuilt" solver you check your policy iteration against.
Do not edit this file during the lab — treat it as ground truth.

Algorithm (standard value iteration):
    V_0(s) = 0 for all s
    repeat:
        Q(s,a) = R(s,a) + discount * sum_s' P(a,s,s') V(s')
        V_new(s) = max_a Q(s,a)
    until max_s |V_new(s) - V(s)| < tolerance
    policy(s) = argmax_a Q(s,a)      <- policy extraction, using the
                                        converged V
"""

import numpy as np

from policy_engine import PolicyEngine, PolicyEngineResult


class ValueIterationEngine(PolicyEngine):

    name = "Value Iteration (reference)"

    def __init__(self, tolerance=1e-8, max_sweeps=10000):
        self.tolerance = tolerance
        self.max_sweeps = max_sweeps

    def solve(self, P, R, discount=0.95, **kwargs):
        A, S, _ = P.shape
        value = np.zeros(S)

        sweep = 0
        for sweep in range(1, self.max_sweeps + 1):
            q_values = self._compute_q(P, R, discount, value)  # (S, A)
            new_value = q_values.max(axis=1)

            delta = np.max(np.abs(new_value - value))
            value = new_value

            if delta < self.tolerance:
                break

        q_values = self._compute_q(P, R, discount, value)
        policy = q_values.argmax(axis=1)

        return PolicyEngineResult(policy, value, sweep, self.name)

    @staticmethod
    def _compute_q(P, R, discount, value):
        """Q(s,a) = R(s,a) + discount * P(a,s,:) . value, stacked to (S, A)."""
        A = P.shape[0]
        return np.stack(
            [R[:, a] + discount * P[a].dot(value) for a in range(A)],
            axis=1,
        )
